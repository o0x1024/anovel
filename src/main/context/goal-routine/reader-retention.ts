export type RetentionWorkType = 'story' | 'novel'

export function retentionPackagingRules(workType: RetentionWorkType): string {
  return [
    '【标题与导语的追读承诺】',
    '- 标题优先表达“外界判断”与“实际结果”的认知反差，或一个结果明确、因果未知的矛盾；不能只是题材名词拼接。',
    '- 导语必须让读者看见具体压力、主角的差异化应对、可持续的核心玩法和第一次兑现方向。',
    '- 标题、导语和正文开局应承诺同一种阅读快感，但三者不能复述同一段场景或台词。',
    workType === 'story'
      ? '- 短故事导语还须给出一个有限篇幅内可以回答的核心问题。'
      : '- 长篇导语只承诺前期兑现与长线矛盾，不得用终局剧透透支悬念。'
  ].join('\n')
}

/**
 * 可迁移的读者留存规则。它描述叙事机制，不绑定任何具体作品、人物或文风，
 * 因而可以安全地用于不同题材的大纲、正文和门禁。
 */
export function retentionPlanningRules(workType: RetentionWorkType): string {
  const cadence = workType === 'story'
    ? '短故事至少每拍完成一次关系、认知、风险或权力状态更新；兑现必须在有限篇幅内可见。'
    : '长篇允许跨章蓄力，但每章仍须产生局部状态更新；同一重大承诺不得连续多章只有提醒而没有进展或阶段兑现。'
  return [
    '【读者留存发动机 - 必须进入因果设计】',
    '- 建立“外界标签/预期”与“人物真实行为准则”的反差；反差必须通过选择被看见，禁止只在人设介绍中宣布。',
    '- 关键场景优先形成“压力逼迫→主角做出有个性的意外选择→选择改变他人判断→关系或局势产生后果”的链条。',
    '- 设计解释差：同一行动至少允许两个重要人物基于各自欲望、旧账和信息作出不同理解；误读必须推动行动，不能只是旁白笑话。',
    '- 每次阶段兑现至少同时改变一项关系资产（信任、亏欠、依赖、忌惮、占有、联盟或敌意），避免只完成事件任务。',
    '- 小兑现与新欠债相连：读者拿到眼前回报后，必须看见由该结果自然产生的新代价、新误会或更大目标。',
    '- 配角不可互换：主要配角各自持有不同欲望、信息或权力，围绕主角接力制造不同性质的压力与吸引。',
    '- 选择一个可回调的私密细节（物件、习惯、称呼、共同记忆）；再次出现时必须改变意义或证明关系变化，不作装饰性复读。',
    `- ${cadence}`,
    '- 不得机械套用多男主、豪门、穿书、热搜、系统或误会；只迁移上述因果机制，并服从当前题材。'
  ].join('\n')
}

export function retentionProseRules(workType: RetentionWorkType): string {
  return [
    '【读者留存执行规则】',
    '- 场景不能只让事件有进展，还要让人物对彼此的判断发生可感知变化；用称呼、站位、资源倾斜、试探、维护或防备呈现。',
    '- 主角吸引力必须来自具体选择及其代价，禁止用“所有人都被美貌/气场震住”代替关系建立。',
    '- 出现误读时，正文先给可观察的言行，再呈现不同人物各自能成立的解释；不要由旁白立刻公布唯一答案。',
    '- 爽点之后保留余波：至少落下一项新的亏欠、秘密、关系变位、风险或待兑现承诺。',
    '- 对话至少承担冲突、试探、信息差、关系变位之一；连续寒暄和重复确认必须压缩。',
    workType === 'story'
      ? '- 本拍结尾必须让读者同时得到一项回报和一个更具体的问题，不能只卡断动作。'
      : '- 本章可以小幅推进，但结尾必须让关系、认知、风险或权力至少一项与章首不同。'
  ].join('\n')
}

export function retentionEvaluationRules(workType: RetentionWorkType): string {
  return [
    '【留存机制验收】',
    '- 人物反差是否由有代价的选择证明，而不是标签、自夸或旁人无依据吹捧？',
    '- 关键行动是否引发至少一个重要人物的判断更新，并进一步改变其行为？',
    '- 解释差是否来自人物各自的信息、欲望和旧账，且确实推进因果；还是所有配角只负责同一种震惊或崇拜？',
    '- 阶段兑现是否同时改写关系，并自然产生新债务；若只有打脸结果、围观反应或强行卡点，则不算完整留存单元。',
    '- 私密细节或前文承诺回调时是否产生新意义，而非原句复读？',
    workType === 'story'
      ? '- 任一节拍若没有关系/认知/风险/权力状态更新，应列为 blocking issue。'
      : '- 连续章节若关系判断不变、承诺无进展或配角功能重复，应列为追读风险。'
  ].join('\n')
}
